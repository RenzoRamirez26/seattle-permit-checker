#!/bin/sh
# Writes src/api/schema.d.ts from FastAPI's OpenAPI document, so the front end cannot drift from api/schemas.py.
# It imports the app and calls nothing: no key, no network.
#   sh scripts/openapi.sh          regenerate
#   sh scripts/openapi.sh --check  fail if the committed file differs from a fresh run (CI)
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
root=$(cd "$here/.." && pwd)
py=${PYTHON:-}
if [ -z "$py" ]; then
  if [ -x "$root/.venv/bin/python" ]; then py="$root/.venv/bin/python"; else py=python; fi
fi
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
(cd "$root" && PYTHON_DOTENV_DISABLED=1 PERMIT_STT=off "$py" -c "import json; from api.main import app; print(json.dumps(app.openapi(), indent=1, sort_keys=True))") > "$tmp/openapi.json"
"$here/node_modules/.bin/openapi-typescript" "$tmp/openapi.json" -o "$tmp/schema.d.ts" >/dev/null
{ echo "// Generated by scripts/openapi.sh from FastAPI's OpenAPI document. Do not edit by hand."; cat "$tmp/schema.d.ts"; } > "$tmp/out.d.ts"
if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$tmp/out.d.ts" "$here/src/api/schema.d.ts"; then
    echo "src/api/schema.d.ts is out of date: run sh scripts/openapi.sh" >&2
    diff "$here/src/api/schema.d.ts" "$tmp/out.d.ts" | head -40 >&2 || true
    exit 1
  fi
  echo "schema.d.ts matches the API"
else
  cp "$tmp/out.d.ts" "$here/src/api/schema.d.ts"
  echo "wrote src/api/schema.d.ts"
fi
